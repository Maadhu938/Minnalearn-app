  static List<Kanji> buildKanjiForLesson(int lessonId) {
    final startIndex = (lessonId - 1) * kanjiPerLesson;
    final endIndex = startIndex + kanjiPerLesson;

    if (startIndex >= _entries.length) {
      return const [];
    }

    return [
      for (int index = startIndex; index < endIndex && index < _entries.length; index++)
        Kanji(
          id: 'lesson_${lessonId}_kanji_${(index - startIndex + 1).toString().padLeft(3, '0')}',
          character: _entries[index]['character']!,
          meaning: _entries[index]['meaning']!,
          onReading: _entries[index]['on']!,
          kunReading: _entries[index]['kun']!,
          lessonId: lessonId,
        ),
    ];
  }
